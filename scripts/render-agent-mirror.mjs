// Renders what a mirror entry's content should be, given its source. Shared by
// the writer (sync-agent-mirrors) and the gate (validate-agent-docs) so there is
// exactly one definition of "correct" and the two cannot disagree.
//
// This is code, not repo data: `scripts/agent-mirrors.mjs` holds the entries and
// is read relative to the working directory, while this module travels with the
// scripts that import it.

import { parse } from 'yaml';

export const MirrorMode = {
  // Frontmatter plus an `@` reference to the source. Cursor documents
  // `@filename` as loading that file into the rule's context and recommends it
  // over copying, so the rule body is never duplicated.
  Stub: 'stub',
  // The whole file. Copilot's path scoping lives in `applyTo`, which exists only
  // in `*.instructions.md`, and GitHub documents `@` references as NOT expanding
  // in that file type — a stub there would leave Copilot a bare path and no rule.
  Copy: 'copy',
};

// Frontmatter keys Cursor actually reads. A stub carries these and nothing else;
// `paths` (Claude) and `applyTo` (Copilot) mean nothing to it.
export const CURSOR_FRONTMATTER_KEYS = ['description', 'globs', 'alwaysApply'];

const FRONTMATTER_PATTERN = /^---\r?\n([\s\S]*?)\r?\n---/;

// The source frontmatter carries comments plus keys for all three tools. A stub
// re-emits only Cursor's keys, serialised from the parsed values, so a reordered
// or re-commented source still produces identical output.
const cursorFrontmatter = (src, source) => {
  const match = FRONTMATTER_PATTERN.exec(src);
  if (!match) throw new Error(`${source} has no frontmatter block, so no stub can be built from it`);

  const parsed = parse(match[1]) ?? {};
  const lines = CURSOR_FRONTMATTER_KEYS.filter((key) => parsed[key] !== undefined).map(
    (key) => `${key}: ${JSON.stringify(parsed[key])}`,
  );

  if (lines.length === 0) throw new Error(`${source} declares none of: ${CURSOR_FRONTMATTER_KEYS.join(', ')}`);
  return lines;
};

export const renderMirror = (src, { source, mode }) => {
  if (mode === MirrorMode.Copy) return src;
  if (mode !== MirrorMode.Stub) throw new Error(`unknown mirror mode \`${mode}\``);

  return [
    '---',
    ...cursorFrontmatter(src, source),
    '---',
    '',
    '<!-- Generated by `npm run sync:agent-mirrors` — edit `' + source + '` instead. -->',
    '',
    `@${source}`,
    '',
  ].join('\n');
};
